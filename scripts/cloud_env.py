#!/usr/bin/env python3
"""Convert a KEY=value env list into a Cloud Run --env-vars-file YAML.

The local install reads .env directly and the hosted service can take the YAML
this prints, so both sides are configured from one file with one set of names:

    python scripts/cloud_env.py .env > /private/path/cloud.env.yaml
    gcloud run deploy ... --env-vars-file /private/path/cloud.env.yaml

Credentials that belong in Secret Manager are refused, not emitted: the live
service mounts them from Secret Manager (docs/RUNBOOK.md), and an env file is
passed to gcloud as a plain argument, which is easy to leak.
"""
import re
import sys
from pathlib import Path

SECRET_MANAGER_ONLY = ("INV_STUDIO_DATABASE_URL", "INV_STUDIO_VAULT_KEY", "INV_STUDIO_AZURE_API_KEY")
# Local-only knobs: Cloud Run sets the port itself and the image fixes the data dir.
LOCAL_ONLY = ("INV_STUDIO_PORT",)
NAME = re.compile(r"^[A-Z][A-Z0-9_]*$")


def parse(text):
    """Read KEY=value lines. Blank values mean "not set" and are skipped."""
    values = {}
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        key, separator, value = line.partition("=")
        key = key.removeprefix("export ").strip()
        if not separator or not NAME.fullmatch(key):
            raise SystemExit(f"line {number}: expected KEY=value, got {raw!r}")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        if value:
            values[key] = value
    return values


def render(values):
    """The YAML lines for gcloud, after the checks an env file must pass."""
    for key in SECRET_MANAGER_ONLY:
        if key in values:
            raise SystemExit(f"{key} must come from Secret Manager, not an env file. Remove it.")
    values = {key: value for key, value in values.items() if key not in LOCAL_ONLY}
    if values.get("INV_STUDIO_CLOUD") != "1":
        raise SystemExit("Set INV_STUDIO_CLOUD=1 for a cloud environment file.")
    for key in ("GOOGLE_CLOUD_PROJECT", "INV_STUDIO_BUCKET", "INV_STUDIO_ALLOWED_EMAILS"):
        if key not in values:
            raise SystemExit(f"{key} is required when INV_STUDIO_CLOUD=1.")
    # Cloud Run keeps its writable state on the container's tmpfs.
    values.setdefault("INV_STUDIO_DATA", "/tmp/inv-studio-data")
    lines = ["# Generated by scripts/cloud_env.py. Keep outside version control."]
    for key in sorted(values):
        # Single-quoted YAML scalars: gcloud requires every value to be a string.
        lines.append(f"{key}: '" + values[key].replace("'", "''") + "'")
    return lines


def main(argv):
    if len(argv) != 2:
        raise SystemExit("usage: cloud_env.py <env-file>")
    for line in render(parse(Path(argv[1]).read_text(encoding="utf-8"))):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
